      // Step 1 - Get user details

let name = prompt("Enter your name:");
let age = Number(prompt("Enter your age:"));
let city = prompt("Enter your city:");


// Step 2 - Get marks

let tamil = Number(prompt("Enter Tamil marks:"));
let english = Number(prompt("Enter English marks:"));
let maths = Number(prompt("Enter Maths marks:"));


// Step 3 - Calculate

let total = tamil + english + maths;
let average = total / 3;


// Step 4 - Check result

let grade;

if (average >= 90) {
    grade = "A";
} else if (average >= 80) {
    grade = "B";
} else if (average >= 70) {
    grade = "C";
} else if (average >= 60) {
    grade = "D";
} else {
    grade = "Fail";
}


// Step 5 - Check voting

let voting;

if (age >= 18) {
    voting = "Eligible";
} else {
    voting = "Not Eligible";
}


// Step 6 - Display

console.log(`
Name: ${name}
Age: ${age}
City: ${city}
Total: ${total}
Average: ${average.toFixed(2)}
Grade: ${grade}
Voting: ${voting}
`);



